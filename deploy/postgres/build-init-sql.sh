#!/usr/bin/env bash
# PLANT-COMMONS: builds deploy/postgres/init.sql, the one-shot schema for an EXTERNAL PostgreSQL (CloudNativePG).
#
# Upstream's database image creates the schema from /docker-entrypoint-initdb.d on first start: database/*.sh
# then database/*.sql in glob order. That mechanism is gone with the platform database, so this script
# concatenates database/*.sql in the same order (checked against the image, see docs/plant-commons/database.md)
# and applies the four changes below. Everything else is upstream's SQL, byte for byte.
#
# init.sql runs ONCE as superuser, in the database <name> (default rsd-db), right after initdb:
#   psql -v ON_ERROR_STOP=1 --single-transaction -U postgres -d rsd-db -f init.sql
# (the platform's mechanism is its own; the file is plain SQL, no psql meta-commands).
#
# Changes to upstream's database/001-setup-basic-roles.sql (each one is asserted, the script fails if upstream
# changed the lines so that a pattern no longer matches exactly once):
#   1. "_database_name_"      -> "<name>"            (000-fill-authenticator-password.sh did this with sed)
#   2. rsd_authenticator is created WITHOUT a password (the platform sets it as a CNPG managed role from its vault)
#   3. ALTER DEFAULT PRIVILEGES gets FOR ROLE <owner>: upstream runs as the owner/superuser of the new database,
#      here the superuser runs it, but the objects must belong to <owner> and get the default privileges
#   4. SET ROLE <owner> after 001 and RESET ROLE at the end: the schema is created BY the owner, so the owner
#      owns every object and later migrations (run as owner) can alter them. 001 itself (CREATE ROLE, GRANT role)
#      needs the superuser, 002..950 do not (verified, docs/plant-commons/database.md).
#
# Also: a file that ends without ";" (upstream's 022) gets one, because the image ran every file separately.
#
# Usage: deploy/postgres/build-init-sql.sh [database-name] [owner-role]     (default: rsd-db rsd)
# Regenerate on EVERY upstream update and commit the result (UPSTREAM.md).
set -euo pipefail

DB_NAME=${1:-rsd-db}
OWNER=${2:-rsd}
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(cd "$HERE/../.." && pwd)
SRC="$REPO_ROOT/database"
OUT="$HERE/init.sql"

[[ $DB_NAME =~ ^[a-z0-9-]+$ ]] || { echo "database name must match [a-z0-9-]+" >&2; exit 1; }
[[ $OWNER =~ ^[a-z_][a-z0-9_]*$ ]] || { echo "owner must match [a-z_][a-z0-9_]*" >&2; exit 1; }

# the image copies *.sql (not *.sql.example) and the entrypoint runs them in glob order; C order is the same
# for these names (checked against the built image)
mapfile -t FILES < <(cd "$SRC" && LC_ALL=C ls -1 -- *.sql | LC_ALL=C sort)
[[ ${FILES[0]} == 001-setup-basic-roles.sql ]] || { echo "first file is ${FILES[0]}, expected 001-setup-basic-roles.sql" >&2; exit 1; }

count() { # count <fixed string> <file>: occurrences
  grep -cF -- "$1" "$2" || true
}
assert_once() {
  [[ $(count "$1" "$2") -eq 1 ]] || { echo "pattern not found exactly once in $2: $1" >&2; exit 1; }
}

ROLES="$SRC/001-setup-basic-roles.sql"
assert_once '"_database_name_"' "$ROLES"
assert_once "CREATE ROLE rsd_authenticator NOINHERIT LOGIN PASSWORD 'POSTGRES_AUTHENTICATOR_PASSWORD';" "$ROLES"
[[ $(count 'ALTER DEFAULT PRIVILEGES IN SCHEMA public' "$ROLES") -eq 3 ]] || { echo "expected 3 ALTER DEFAULT PRIVILEGES in 001" >&2; exit 1; }
# nothing else in database/ may depend on the entrypoint's env substitution
if grep -lE '_database_name_|POSTGRES_AUTHENTICATOR_PASSWORD|\$\{?POSTGRES_' "$SRC"/*.sql | grep -v '001-setup-basic-roles.sql'; then
  echo "another SQL file uses placeholders; extend this script" >&2; exit 1
fi

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
{
  echo "-- PLANT-COMMONS: GENERATED by deploy/postgres/build-init-sql.sh, do not edit. Regenerate on every upstream update."
  echo "-- Source: database/*.sql of the imported RSD release (see UPSTREAM.md). Database: \"$DB_NAME\", owner role: $OWNER."
  echo "-- Run ONCE as superuser in database \"$DB_NAME\" after initdb. Plain SQL, no psql meta-commands."
  echo
  for f in "${FILES[@]}"; do
    echo "-- ===== $f ====="
    if [[ $f == 001-setup-basic-roles.sql ]]; then
      sed \
        -e "s/\"_database_name_\"/\"$DB_NAME\"/" \
        -e "s/^CREATE ROLE rsd_authenticator NOINHERIT LOGIN PASSWORD 'POSTGRES_AUTHENTICATOR_PASSWORD';/-- PLANT-COMMONS: no password here, the platform sets it (CNPG managed role)\nCREATE ROLE rsd_authenticator NOINHERIT LOGIN;/" \
        -e "s/^ALTER DEFAULT PRIVILEGES IN SCHEMA public/ALTER DEFAULT PRIVILEGES FOR ROLE $OWNER IN SCHEMA public/" \
        "$SRC/$f"
      echo
      echo "-- PLANT-COMMONS: from here on the schema is created by the owner role (owns the objects, holds the default privileges above)"
      echo "SET ROLE $OWNER;"
    else
      cat "$SRC/$f"
    fi
    # The image runs every file on its own, so a file may end without ";" (022 does). Concatenated, that would
    # glue its last statement to the next file, so terminate it. Only the last character is checked: a file
    # ending in a comment would need a smarter rule, the build fails on that case.
    body=$(<"$SRC/$f")   # command substitution drops trailing newlines
    body=${body%"${body##*[![:space:]]}"}
    if [[ ${body: -1} != ";" ]]; then
      if [[ ${body##*$'\n'} == --* ]]; then
        echo "$f ends in a comment without ';', extend this script" >&2; exit 1
      fi
      echo "note: terminating $f with ';'" >&2
      printf '\n;\n'
    fi
    echo
  done
  echo "RESET ROLE;"
} >"$TMP"

# the transformed 001 must not contain any placeholder any more
if grep -nE '_database_name_|POSTGRES_AUTHENTICATOR_PASSWORD' "$TMP"; then
  echo "placeholders left in the output" >&2; exit 1
fi
mv "$TMP" "$OUT"
trap - EXIT
echo "wrote $OUT ($(wc -c <"$OUT") bytes, ${#FILES[@]} files)"
